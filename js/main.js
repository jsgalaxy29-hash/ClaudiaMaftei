const getQueryParams = () => {
  if (window.location.search) {
    return new URLSearchParams(window.location.search);
  }

  const hash = window.location.hash;
  if (hash.includes('?')) {
    const queryString = hash.split('?')[1];
    return new URLSearchParams(queryString);
  }

  return new URLSearchParams();
};

const setActiveLanguage = (lang) => {
  const langButtons = document.querySelectorAll('[data-lang]');
  langButtons.forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.lang === lang));
  });
};

const applyTranslations = (lang) => {
  const language = translations[lang] ? lang : 'fr';
  document.documentElement.setAttribute('lang', language);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const value = translations[language]?.[el.dataset.i18n];
    if (value) {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const value = translations[language]?.[el.dataset.i18nHtml];
    if (value) {
      el.innerHTML = value;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const value = translations[language]?.[el.dataset.i18nPlaceholder];
    if (value) {
      el.setAttribute('placeholder', value);
    }
  });

  document.querySelectorAll('[data-i18n-content]').forEach((el) => {
    const value = translations[language]?.[el.dataset.i18nContent];
    if (value) {
      el.setAttribute('content', value);
    }
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    const value = translations[language]?.[el.dataset.i18nAlt];
    if (value) {
      el.setAttribute('alt', value);
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const value = translations[language]?.[el.dataset.i18nAriaLabel];
    if (value) {
      el.setAttribute('aria-label', value);
    }
  });

  setActiveLanguage(language);
  return language;
};

const params = getQueryParams();
const storedLang = window.localStorage.getItem('siteLanguage');
const defaultLang = document.documentElement.getAttribute('lang') || 'fr';
const queryLang = params.get('lang');
const initialLang =
  (queryLang && translations[queryLang] ? queryLang : null) || storedLang || defaultLang;
const activeLang = applyTranslations(initialLang);
window.localStorage.setItem('siteLanguage', activeLang);

document.querySelectorAll('[data-lang]').forEach((button) => {
  button.addEventListener('click', () => {
    const nextLang = button.dataset.lang;
    if (!translations[nextLang]) {
      return;
    }
    applyTranslations(nextLang);
    window.localStorage.setItem('siteLanguage', nextLang);
  });
});

const contactSection = document.getElementById('contact');
const contactForm = contactSection?.querySelector('form');

if (contactSection && contactForm && (params.has('sent') || params.has('error'))) {
  const message = document.createElement('div');
  if (params.get('sent') === '1') {
    message.className = 'flash flash-success';
    message.textContent = translations[activeLang].contact_success_message;
  } else {
    message.className = 'flash flash-error';
    message.textContent = translations[activeLang].contact_error_message;
  }
  contactForm.parentElement?.insertBefore(message, contactForm);

  const cleanUrl = `${window.location.pathname}${window.location.hash.split('?')[0] || ''}`;
  window.history.replaceState({}, document.title, cleanUrl);
}
